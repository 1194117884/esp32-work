/* ---- I2C 写命令 ---- */
static void i2c_write_cmd(uint8_t *data, size_t len)
{
    i2c_cmd_handle_t cmd = i2c_cmd_link_create();
    i2c_master_start(cmd);
    i2c_master_write_byte(cmd, (SSD1306_I2C_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write(cmd, data, len, true);
    i2c_master_stop(cmd);
    i2c_master_cmd_begin(I2C_PORT, cmd, pdMS_TO_TICKS(100));
    i2c_cmd_link_delete(cmd);
}

/* ---- 发送命令 ---- */
static void ssd1306_write_cmd(uint8_t cmd)
{
    uint8_t data[] = {0x00, cmd};  /* 0x00 = 命令模式 */
    i2c_write_cmd(data, 2);
}

/* ---- 发送数据 ---- */
static void ssd1306_write_data(uint8_t *data, size_t len)
{
    uint8_t *buf = malloc(len + 1);
    buf[0] = 0x40;  /* 0x40 = 数据模式 */
    memcpy(buf + 1, data, len);
    i2c_write_cmd(buf, len + 1);
    free(buf);
}

/* ---- 初始化 ---- */
void ssd1306_init(void)
{
    ESP_LOGI(TAG, "初始化 I2C (SCL=GPIO%d, SDA=GPIO%d)", I2C_SCL_IO, I2C_SDA_IO);

    /* I2C 配置 */
    i2c_config_t conf = {
        .mode = I2C_MODE_MASTER,
        .sda_io_num = I2C_SDA_IO,
        .scl_io_num = I2C_SCL_IO,
        .sda_pullup_en = GPIO_PULLUP_ENABLE,
        .scl_pullup_en = GPIO_PULLUP_ENABLE,
        .master.clk_speed = I2C_FREQ,
    };
    i2c_param_config(I2C_PORT, &conf);
    i2c_driver_install(I2C_PORT, conf.mode, 0, 0, 0);

    /* 扫描 I2C 总线 */
    ESP_LOGI(TAG, "扫描 I2C 设备...");
    for (uint8_t addr = 1; addr < 127; addr++) {
        i2c_cmd_handle_t cmd = i2c_cmd_link_create();
        i2c_master_start(cmd);
        i2c_master_write_byte(cmd, (addr << 1) | I2C_MASTER_WRITE, true);
        i2c_master_stop(cmd);
        esp_err_t ret = i2c_master_cmd_begin(I2C_PORT, cmd, pdMS_TO_TICKS(20));
        if (ret == ESP_OK) {
            ESP_LOGI(TAG, "找到 I2C 设备: 0x%02X", addr);
        }
        i2c_cmd_link_delete(cmd);
        vTaskDelay(pdMS_TO_TICKS(1));
    }

    /* SSD1306 初始化序列 */
    ssd1306_write_cmd(0xAE);  // display off
    ssd1306_write_cmd(0xD5);  // set display clock div
    ssd1306_write_cmd(0x80);
    ssd1306_write_cmd(0xA8);  // set multiplex
    ssd1306_write_cmd(SSD1306_HEIGHT - 1);
    ssd1306_write_cmd(0xD3);  // set display offset
    ssd1306_write_cmd(0x00);
    ssd1306_write_cmd(0x40);  // set start line
    ssd1306_write_cmd(0x8D);  // set charge pump
    ssd1306_write_cmd(0x14);
    ssd1306_write_cmd(0x20);  // set memory mode
    ssd1306_write_cmd(0x00);  // horizontal
    ssd1306_write_cmd(0xA1);  // segment remap
    ssd1306_write_cmd(0xC8);  // COM scan direction
    ssd1306_write_cmd(0xDA);  // set COM pins
    ssd1306_write_cmd(0x02);
    ssd1306_write_cmd(0x81);  // set contrast
    ssd1306_write_cmd(0xCF);
    ssd1306_write_cmd(0xD9);  // set precharge
    ssd1306_write_cmd(0xF1);
    ssd1306_write_cmd(0xDB);  // set VCOMH deselect
    ssd1306_write_cmd(0x40);
    ssd1306_write_cmd(0xA4);  // output RAM to display
    ssd1306_write_cmd(0xA6);  // normal display (not inverted)
    ssd1306_write_cmd(0xAF);  // display on

    /* 全屏点亮测试: 确保显示正常 */
    memset(framebuffer, 0xFF, sizeof(framebuffer));
    ssd1306_refresh();
    vTaskDelay(pdMS_TO_TICKS(500));
    ssd1306_clear();
    ssd1306_refresh();

    ESP_LOGI(TAG, "SSD1306 初始化完成 (%dx%d)", SSD1306_WIDTH, SSD1306_HEIGHT);
}

/* ---- 清屏 ---- */
void ssd1306_clear(void)
{
    memset(framebuffer, 0, sizeof(framebuffer));
}

/* ---- 刷新显示 ---- */
void ssd1306_refresh(void)
{
    for (int page = 0; page < SSD1306_PAGES; page++) {
        ssd1306_write_cmd(0xB0 + page);  /* 设置页地址 */
        ssd1306_write_cmd(0x00);          /* 列低地址 */
        ssd1306_write_cmd(0x10);          /* 列高地址 */
        ssd1306_write_data(framebuffer[page], SSD1306_WIDTH);
    }
}

/* ---- 画点 ---- */
void ssd1306_set_pixel(int x, int y, int on)
{
    if (x < 0 || x >= SSD1306_WIDTH || y < 0 || y >= SSD1306_HEIGHT) return;
    if (on)
        framebuffer[y / 8][x] |= (1 << (y % 8));
    else
        framebuffer[y / 8][x] &= ~(1 << (y % 8));
}

/* ---- 画空心矩形 ---- */
void ssd1306_draw_rect(int x, int y, int w, int h, int on)
{
    for (int i = 0; i < w; i++) {
        ssd1306_set_pixel(x + i, y, on);
        ssd1306_set_pixel(x + i, y + h - 1, on);
    }
    for (int i = 0; i < h; i++) {
        ssd1306_set_pixel(x, y + i, on);
        ssd1306_set_pixel(x + w - 1, y + i, on);
    }
}

/* ---- 画实心矩形 ---- */
void ssd1306_fill_rect(int x, int y, int w, int h, int on)
{
    for (int i = 0; i < w; i++)
        for (int j = 0; j < h; j++)
            ssd1306_set_pixel(x + i, y + j, on);
}

/* ---- 画一个 5x7 字符 ---- */
void ssd1306_put_char(int x, int y, char c)
{
    if (c < 32 || c > 126) c = ' ';
    const uint8_t *glyph = font5x7[c - 32];
    for (int col = 0; col < 5; col++) {
        uint8_t line = glyph[col];
        for (int row = 0; row < 7; row++) {
            ssd1306_set_pixel(x + col, y + row, (line >> row) & 1);
        }
    }
}

/* ---- 画字符串 ---- */
void ssd1306_put_string(int x, int y, const char *str)
{
    while (*str) {
        ssd1306_put_char(x, y, *str);
        x += 6;  /* 5px 字宽 + 1px 间距 */
        if (x > SSD1306_WIDTH - 5) break;
        str++;
    }
}